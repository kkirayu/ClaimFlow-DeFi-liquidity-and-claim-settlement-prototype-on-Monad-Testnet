import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'contracts', 'out');
const TARGET = path.join(ROOT, 'frontend', 'src', 'lib', 'abis.generated.ts');

const contracts = ['MockUSDC', 'LiquidityVault', 'ClaimManager'];
const exports = [];

for (const name of contracts) {
  const file = path.join(OUT, `${name}.sol`, `${name}.json`);
  if (!fs.existsSync(file)) {
    throw new Error(`Missing artifact ${file}. Run "pnpm contracts:build" first.`);
  }
  const artifact = JSON.parse(fs.readFileSync(file, 'utf8'));
  exports.push(
    `export const ${name.charAt(0).toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(
      artifact.abi,
      null,
      2,
    )} as const;`,
  );
}

const header = `// AUTO-GENERATED by scripts/sync-abis.mjs from Foundry artifacts.
// Do not edit by hand. Run "pnpm contracts:build && pnpm sync:abis" after changing contracts.

`;

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, `${header}${exports.join('\n\n')}\n`);
console.log(`Wrote ${TARGET}`);
